<?php

declare(strict_types=1);

namespace App\ApiAdmin\Pages;

use App\ApiAdmin\Fields\RestHasMany;
use App\ApiAdmin\Fields\RestHasOne;
use App\ApiAdmin\Resources\AbstractRestResource;
use App\ApiAdmin\Validation\HostedValidationRules;
use Illuminate\Contracts\Validation\Rule;
use Illuminate\Contracts\Validation\ValidationRule;
use MoonShine\Contracts\Core\DependencyInjection\CoreContract;
use MoonShine\Contracts\UI\ComponentContract;
use MoonShine\Contracts\UI\FieldContract;
use MoonShine\Crud\Collections\Fields;
use MoonShine\Crud\Components\Fragment;
use MoonShine\Crud\Pages\FormPage as CrudFormPage;
use MoonShine\UI\Components\Layout\Divider;
use MoonShine\UI\Components\Layout\LineBreak;
use Override;
use Stringable;
use Throwable;

/**
 * Form page for REST resources — renders outside relation fields
 * (RestHasOne / RestHasMany) AFTER the main form. The main form itself wraps
 * its fields in Box via the page's fields() method (native MoonShine pattern),
 * not via a mainLayer() override.
 *
 * Generic params propagate the parent CrudFormPage shape so the per-resource
 * subclasses generated by ResourceGenerator can declare
 * `@extends RestFormPage<PostResource>` and have phpstan resolve
 * `$this->getResource()` to the concrete resource type.
 *
 * @template TResource of AbstractRestResource = AbstractRestResource
 *
 * @extends CrudFormPage<
 *     TResource,
 *     mixed,
 *     CoreContract,
 *     Fields
 * >
 */
abstract class RestFormPage extends CrudFormPage
{
    /** @return array<string, string|list<string|ValidationRule|Rule|Stringable>> */
    #[Override]
    public function getRules(): array
    {
        $rules = parent::getRules();
        HostedValidationRules::assertMap($rules);

        return $rules;
    }

    /**
     * @return list<ComponentContract>
     *
     * @throws Throwable
     */
    #[Override]
    protected function bottomLayer(): array
    {
        $components = parent::bottomLayer();

        if (! $this->isItemExists()) {
            return $components;
        }

        $resource = $this->getResource();
        if (! $resource instanceof AbstractRestResource) {
            return $components;
        }

        $outsideFields = $resource->getOutsideFields()->formFields();

        if ($outsideFields->isEmpty()) {
            return $components;
        }

        $item = $resource->getCastedData();

        $components[] = Divider::make();

        /** @var FieldContract $field */
        foreach ($outsideFields as $field) {
            if (! $field instanceof RestHasOne && ! $field instanceof RestHasMany) {
                continue;
            }

            $components[] = LineBreak::make();

            $components[] = Fragment::make([
                $field->fillCast(
                    $item,
                    $resource->getCaster(),
                ),
            ])
                ->name('rest-'.$field->getColumn())
                ->canSee(static fn (): bool => $field->isSee());
        }

        return $components;
    }
}
